/**
 * Модел на училище от API-то на ИСОДЗ.
 * Съдържа основна информация за училището и наличните места.
 */
export interface School {
  /** Уникален идентификатор на училището в системата */
  id: number;

  /** Наименование на училището */
  nameStr: string;

  /** Район на училището */
  region: string;

  /** Брой свободни места за класиране */
  free: number;

  /** Брой записани деца */
  signed: number;

  /** Брой незаписани (класирани, но незаписани) деца */
  unsigned: number;

  /** Общ капацитет на училището */
  capacity: number;

  /** Налични места (може да се различава от free) */
  available: number;
}

/** Отговор от API за списък с училища */
export interface SchoolsResponse {
  items: School[];
}
