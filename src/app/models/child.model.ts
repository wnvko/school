/**
 * Модел на друго училище, в което дете е кандидатствало.
 * Вложен обект в Child — показва останалите желания на детето.
 */
export interface OtherSchool {
  /** Идентификатор на училището */
  schoolId: number;

  /** Точки на детето за това училище */
  points: number;

  /** Пореден номер на желанието (1 = първо желание) */
  wishOrder: number;
}

/**
 * Модел на дете от API-то на ИСОДЗ.
 * Представлява записа на дете за конкретно училище в waitlist-а.
 */
export interface Child {
  /** Уникален идентификатор на записа */
  id: number;

  /** Идентификатор на училището, за което е кандидатурата */
  schoolId: number;

  /** Номер на детето в системата (идентифицира уникално детето) */
  childNum: number;

  /** Име на детето */
  name: string;

  /** Текстово описание на групата (напр. "Първа група с допълнителни критерии") */
  displayText: string;

  /** Точки от допълнителни критерии */
  points: number;

  /** Пореден номер на желанието за това училище */
  wishOrder: number;

  /**
   * Класиране/позиция на детето в списъка на училището.
   * Генерирано от системата на ИСОДЗ (включва случайно число за гранична група).
   */
  order: number;

  /** Останалите училища, в които детето е кандидатствало */
  otherSchools: OtherSchool[];
}

/** Отговор от API за списък с деца */
export interface ChildrenResponse {
  items: Child[];
}
