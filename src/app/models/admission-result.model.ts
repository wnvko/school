/**
 * Резултат от симулацията на класирането за едно желание на дете.
 * Всяко дете има толкова записа, колкото са желанията му —
 * по един за всяко училище, което е посочило.
 */
export interface AdmissionResult {
  /** Номер на детето в системата */
  childNum: number;

  /** Име на детето */
  name: string;

  /** Идентификатор на училището */
  schoolId: number;

  /** Наименование на училището */
  schoolName: string;

  /** Брой свободни места в училището (от school.free) */
  schoolCapacity: number;

  /** Точки от допълнителни критерии */
  points: number;

  /** Пореден номер на желанието (1 = първо желание) */
  wishOrder: number;

  /** Позиция в класирането на училището (от API) */
  order: number;

  /**
   * Номер на групата по водещ критерий:
   * 1 = Първа група, 2 = Втора, 3 = Трета, 4 = Четвърта
   */
  group: number;

  /** Текстово описание на групата */
  displayText: string;

  /** Дали детето е прието в това училище при симулацията */
  admitted: boolean;
}
