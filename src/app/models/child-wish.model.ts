/**
 * Желание на дете — използва се за показване и пренареждане
 * на желанията в навигационния панел.
 */
export interface ChildWish {
  /** Идентификатор на училището */
  schoolId: number;

  /** Наименование на училището */
  schoolName: string;

  /** Пореден номер на желанието */
  wishOrder: number;

  /** Точки от допълнителни критерии за това училище */
  points: number;

  /** Позиция в класирането (от API) */
  order: number;
}
